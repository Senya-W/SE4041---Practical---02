// Worked example
let mark = 68
if mark >= 75 {
    print("Distinction")
} else if mark >= 50 {
    print("Pass")
} else {
    print("Fail")
}
// Output: Pass

// Activity 4 – Attendance
let attendance = 78      // try 95, 85, 78, 60

if attendance >= 90 {
    print("Excellent attendance")
} else if attendance >= 80 {
    print("Good attendance")
} else if attendance >= 70 {
    print("Acceptable attendance")
} else {
    print("Low attendance")
}
// attendance = 78 -> Acceptable attendance
